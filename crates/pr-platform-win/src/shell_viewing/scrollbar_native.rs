//! Port of `PhotoReview.Shell.Win32/Viewing/ScrollBarNative.cs` (WP-26): the two user32 calls the self-drawn scroll bars need
//! (mouse-leave tracking, the system keyboard repeat timing) plus two message constants. Baseline `d92d6aae`.
//!
//! `repeat_timing_for` is pure and golden-tested; `repeat_timing` and `track_mouse_leave` are the only parts that touch the OS.
//! Decision D-W8-16e-2: window handles are `isize` here (the C# `nint`); the `windows` crate `HWND` stays inside the function
//! bodies, so `pr_app` can pass a handle it got from a `WindowOps` implementation without depending on the `windows` crate.

use windows::Win32::Foundation::HWND;
use windows::Win32::UI::Input::KeyboardAndMouse::{TME_LEAVE, TRACKMOUSEEVENT, TrackMouseEvent};
use windows::Win32::UI::WindowsAndMessaging::{
    SPI_GETKEYBOARDDELAY, SPI_GETKEYBOARDSPEED, SYSTEM_PARAMETERS_INFO_UPDATE_FLAGS, SystemParametersInfoW,
};

/// `WM_MOUSELEAVE` (generated by `TrackMouseEvent(TME_LEAVE)`).
pub const WM_MOUSE_LEAVE: u32 = 0x02A3;

/// `WM_CANCELMODE`: the system forces every mouse loop / capture to end (a modal dialog appears).
pub const WM_CANCEL_MODE: u32 = 0x001F;

/// C# `TrackMouseLeave(hwnd)`: asks for ONE `WM_MOUSELEAVE` when the pointer leaves the client area of `hwnd`
/// (`TrackMouseEvent` with `TME_LEAVE`, `cbSize = size_of::<TRACKMOUSEEVENT>()`, `dwHoverTime = 0`). The result of the call is
/// ignored (C# `_ =`): an invalid handle is a silent no-op, never a panic or an error.
pub fn track_mouse_leave(hwnd: isize) {
    let mut data = TRACKMOUSEEVENT {
        cbSize: size_of::<TRACKMOUSEEVENT>() as u32,
        dwFlags: TME_LEAVE,
        hwndTrack: HWND(hwnd as *mut core::ffi::c_void),
        dwHoverTime: 0,
    };
    // SAFETY: `data` is a local, fully initialised `TRACKMOUSEEVENT` whose `cbSize` is its own size; the pointer is valid for the
    // whole call and the call does not keep it. An invalid `hwndTrack` only makes the call fail, and that result is ignored.
    let _ = unsafe { TrackMouseEvent(&mut data) };
}

/// C# `RepeatTiming()`: `(delay_ms, interval_ms)` of the WPF `RepeatButton` from the system. Reads `SPI_GETKEYBOARDDELAY` into a
/// delay that must be `0..=3` (else 0) and `SPI_GETKEYBOARDSPEED` into a speed that must be `0..=31` (else 31); a failing call
/// also gives the fallback. Then `repeat_timing_for(delay, speed)`.
pub fn repeat_timing() -> (i32, i32) {
    let mut delay: i32 = 0;
    // SAFETY: `pvParam` points to the local `i32` `delay`, which outlives the call; `SPI_GETKEYBOARDDELAY` writes one `INT`.
    let delay_ok = unsafe {
        SystemParametersInfoW(
            SPI_GETKEYBOARDDELAY,
            0,
            Some((&mut delay as *mut i32).cast()),
            SYSTEM_PARAMETERS_INFO_UPDATE_FLAGS(0),
        )
    }
    .is_ok();
    if !delay_ok || !(0..=3).contains(&delay) {
        delay = 0;
    }

    let mut speed: i32 = 31;
    // SAFETY: `pvParam` points to the local `i32` `speed`, which outlives the call; `SPI_GETKEYBOARDSPEED` writes one `UINT`/`INT`.
    let speed_ok = unsafe {
        SystemParametersInfoW(
            SPI_GETKEYBOARDSPEED,
            0,
            Some((&mut speed as *mut i32).cast()),
            SYSTEM_PARAMETERS_INFO_UPDATE_FLAGS(0),
        )
    }
    .is_ok();
    if !speed_ok || !(0..=31).contains(&speed) {
        speed = 31;
    }

    repeat_timing_for(delay, speed)
}

/// C# `RepeatTimingFor(keyboardDelay, keyboardSpeed)` = `((delay + 1) * 250, ((31 - speed) * (400 - 33) / 31) + 33)` in C# `int`
/// (unchecked: use `wrapping_*`; the division truncates toward zero like Rust's `/`). No range check: out-of-range input is
/// formula output.
pub const fn repeat_timing_for(keyboard_delay: i32, keyboard_speed: i32) -> (i32, i32) {
    (
        keyboard_delay.wrapping_add(1).wrapping_mul(250),
        (31i32.wrapping_sub(keyboard_speed).wrapping_mul(367) / 31).wrapping_add(33),
    )
}
