/// The truncation schedule of C# `TryRead_EveryTruncationOfAThumbnailJpeg_NeverThrows`: every length below 700, then
/// every ninth one up to the full length.
fn truncation_lengths(full_length: usize) -> Vec<usize> {
    let mut lengths = Vec::new();
    let mut length = 0;
    while length < full_length {
        lengths.push(length);
        length += if length < 700 { 1 } else { 9 };
    }
    lengths
}

/// Deterministic xorshift-free generator for the mutation tests (the C# `Random(31)` sequence is not reproduced; the
/// assertions hold for any seed).
struct Lcg(u64);

impl Lcg {
    fn next_u32(&mut self) -> u32 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        (self.0 >> 33) as u32
    }

    /// Uniform in `0..n`; `n` must be positive.
    fn below(&mut self, n: usize) -> usize {
        self.next_u32() as usize % n
    }

    fn byte(&mut self) -> u8 {
        self.next_u32() as u8
    }
}

/// Port of C# `JpegBytes.Mutate` (Robustness/JpegBytes.cs): 1..3 random structural or bit-level mutations.
fn mutate(rng: &mut Lcg, input: &[u8]) -> Vec<u8> {
    let mut data = input.to_vec();
    let rounds = 1 + rng.below(3);
    for _ in 0..rounds {
        if data.is_empty() {
            data.push(rng.byte());
            continue;
        }
        match rng.below(9) {
            0 => {
                let i = rng.below(data.len());
                data[i] = rng.byte();
            }
            1 => {
                let i = rng.below(data.len());
                data[i] ^= 1 << rng.below(8);
            }
            2 => {
                let pos = rng.below(data.len());
                let n = (1 + rng.below(8)).min(data.len() - pos);
                data.drain(pos..pos + n);
            }
            3 => {
                let at = rng.below(data.len() + 1);
                let n = 1 + rng.below(8);
                for k in 0..n {
                    let b = rng.byte();
                    data.insert(at + k, b);
                }
            }
            4 => {
                let keep = rng.below(data.len() + 1);
                data.truncate(keep);
            }
            5 => {
                let i = rng.below(data.len());
                data[i] = 0xFF;
            }
            6 => {
                let i = rng.below(data.len());
                data[i] = 0x00;
            }
            7 => {
                let start = rng.below(data.len());
                let len = (1 + rng.below(23)).min(data.len() - start);
                let slice = data[start..start + len].to_vec();
                let at = rng.below(data.len() + 1);
                for (k, b) in slice.into_iter().enumerate() {
                    data.insert(at + k, b);
                }
            }
            _ => {
                let pos = rng.below(data.len());
                let extreme: [u8; 2] = match rng.below(3) {
                    0 => [0xFF, 0xFF],
                    1 => [0x7F, 0xFF],
                    _ => [0x00, 0x00],
                };
                for (i, b) in extreme.iter().enumerate() {
                    if pos + i < data.len() {
                        data[pos + i] = *b;
                    }
                }
            }
        }
    }
    data
}

/// The APP1 segment `(start, end)` of a JPEG (C# `DecodingHelpersMutationTests` / `MutatedApp1_NeverThrows` scan).
/// `(0, 0)` when there is none.
fn app1_range(jpeg: &[u8]) -> (usize, usize) {
    let mut at = 2usize;
    while at + 4 <= jpeg.len() && jpeg[at] == 0xFF {
        let len = (usize::from(jpeg[at + 2]) << 8) | usize::from(jpeg[at + 3]);
        if jpeg[at + 1] == 0xE1 {
            return (at, at + 2 + len);
        }
        at += 2 + len;
    }
    (0, 0)
}

