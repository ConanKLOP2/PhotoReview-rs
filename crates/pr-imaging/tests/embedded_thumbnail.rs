fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Reads a committed fixture and checks length and sha256 against the manifest before any test uses it (contract
/// wiring note 4: JPEG encoder output is not bit-stable between Windows builds, so the committed bytes are the truth).
fn fixture_bytes(name: &str) -> Vec<u8> {
    let manifest = golden::load("embedded-thumbnail-fixtures");
    let entry = manifest
        .cases
        .iter()
        .find(|c| str_of(c, "file") == name)
        .unwrap_or_else(|| panic!("fixture {name} is not in embedded-thumbnail-fixtures.json"));
    let bytes = std::fs::read(fixture_dir().join(name)).unwrap_or_else(|e| panic!("read fixture {name}: {e}"));
    assert_eq!(bytes.len() as i64, i64_of(entry, "length"), "fixture {name}: length");
    assert_eq!(hex(&sha256(&bytes)), str_of(entry, "sha256"), "fixture {name}: sha256");
    bytes
}

/// Bytes for the fake backend, which never parses them.
fn fake_bytes() -> &'static [u8] {
    b"the fake backend decides what this container is"
}

/// The truncation schedule of C# `TryRead_EveryTruncationOfAThumbnailJpeg_NeverThrows`: every length below 700, then
/// every ninth one up to the full length.
fn truncation_lengths(full_length: usize) -> Vec<usize> {
    let mut lengths = Vec::new();
    let mut length = 0;
    while length < full_length {
        lengths.push(length);
        length += if length < 700 { 1 } else { 9 };
    }
    lengths
}

