#[test]
fn try_read_orientation_matrix_matches_golden_with_fake_backend() {
    // golden: embedded-thumbnail-read.json, the `quad-orientation-*` and `quad-no-orientation` cases (11). Sizes,
    // orientation and original size come from the golden; the fake frame reports the golden's orientation.
    let golden = golden::load("embedded-thumbnail-read");
    let mut checked = 0;
    let mut problems = Vec::new();
    for case in golden.cases.iter().filter(|c| {
        c.get("kind").and_then(Value::as_str).unwrap_or("file") == "file"
            && (str_of(c, "file").starts_with("quad-orientation-") || str_of(c, "file") == "quad-no-orientation.jpg")
    }) {
        let name = str_of(case, "name");
        let expected = case
            .get("result")
            .filter(|v| !v.is_null())
            .unwrap_or_else(|| panic!("{name}: the golden has a result"));
        let orientation = i32::try_from(i64_of(expected, "orientation")).expect("orientation fits i32");
        let bytes = fixture_bytes(str_of(case, "file"));
        let run = read_fake(thumb(16, 8, orientation), &bytes);
        let image = expect_image(run.result);
        let got = [
            (
                "width",
                image.pixel_width().to_string(),
                i64_of(expected, "width").to_string(),
            ),
            (
                "height",
                image.pixel_height().to_string(),
                i64_of(expected, "height").to_string(),
            ),
            (
                "orientation",
                image.orientation().to_string(),
                i64_of(expected, "orientation").to_string(),
            ),
            (
                "original_width",
                image.original_width().to_string(),
                i64_of(expected, "original_width").to_string(),
            ),
            (
                "original_height",
                image.original_height().to_string(),
                i64_of(expected, "original_height").to_string(),
            ),
            (
                "estimated_bytes",
                image.estimated_bytes().to_string(),
                i64_of(expected, "estimated_bytes").to_string(),
            ),
        ];
        for (key, actual, want) in got {
            if actual != want {
                problems.push(format!("{name}: {key} want {want} got {actual}"));
            }
        }
        checked += 1;
    }
    assert_eq!(checked, 11, "the golden holds 11 orientation cases");
    assert!(
        problems.is_empty(),
        "orientation matrix differs:\n{}",
        problems.join("\n")
    );
}

