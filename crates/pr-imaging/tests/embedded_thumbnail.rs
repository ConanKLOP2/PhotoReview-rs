/// Outcome of one fake read: the result, the backend trace and the fake file system (for open counts).
struct Run {
    result: Result<Option<DecodedImage>, BlankPath>,
    trace: Arc<Trace>,
    fs: FakeFileSystem,
}

/// Runs `try_read` on a fake file system holding `bytes` at `JPEG_PATH`, with a fake backend over `container`.
fn read_fake(container: Container, bytes: &[u8]) -> Run {
    let fs = FakeFileSystem::new();
    fs.add_file(JPEG_PATH, bytes);
    let trace = Arc::new(Trace::default());
    let backend = FakeBackend {
        container,
        trace: Arc::clone(&trace),
        min_bytes: 0,
    };
    let codec = fake_codec();
    let result = try_read(Path::new(JPEG_PATH), &fs, &backend, codec.as_ref());
    Run { result, trace, fs }
}

fn expect_image(result: Result<Option<DecodedImage>, BlankPath>) -> DecodedImage {
    match result {
        Ok(Some(image)) => image,
        Ok(None) => panic!("expected an image, got None"),
        Err(e) => panic!("expected an image, got the error: {e}"),
    }
}

/// The BGRA bytes at `(x, y)` of a Pbgra32 platform image.
fn bgra_at(image: &DecodedImage, x: i32, y: i32) -> [u8; 4] {
    let px = image
        .platform_image()
        .as_pixels()
        .unwrap_or_else(|| panic!("platform image is not a PixelBuffer"));
    assert_eq!(px.layout(), PixelLayout::Pbgra32, "layout");
    let row = px.get_row(y).unwrap_or_else(|_| panic!("row {y} is not readable"));
    let o = x as usize * 4;
    [row[o], row[o + 1], row[o + 2], row[o + 3]]
}

