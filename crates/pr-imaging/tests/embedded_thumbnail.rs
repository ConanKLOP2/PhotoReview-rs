/// What the fake container reports when it is opened.
#[derive(Clone)]
enum Container {
    /// `backend.open` refuses: not an image, damaged header (every such case maps to "no thumbnail").
    Refused,
    /// `backend.open` succeeds with zero frames.
    NoFrames,
    /// Frame 0 with the given header, thumbnail and orientation.
    Frame(FrameSpec),
}

#[derive(Clone)]
struct FrameSpec {
    /// The MAIN frame's header size, or the error the backend reports.
    main: Result<(u32, u32), &'static str>,
    thumbnail: Option<BitmapSpec>,
    /// Orientation 1..=8 as the frame reports it (the frame normalises; the reader does not).
    orientation: i32,
}

#[derive(Clone)]
struct BitmapSpec {
    /// The thumbnail's claimed size, or the error the backend reports.
    size: Result<(u32, u32), &'static str>,
    /// Written for every pixel by `copy_pbgra`.
    fill: [u8; 4],
    /// `copy_pbgra` fails.
    copy_error: bool,
}

/// One frame-0 thumbnail with the default main size 48x32 and a blue fill.
fn thumb(width: u32, height: u32, orientation: i32) -> Container {
    Container::Frame(FrameSpec {
        main: Ok((48, 32)),
        thumbnail: Some(BitmapSpec {
            size: Ok((width, height)),
            fill: BLUE,
            copy_error: false,
        }),
        orientation,
    })
}

/// What the reader asked for, in order, and how often each step ran.
#[derive(Default)]
struct Trace {
    steps: Mutex<Vec<&'static str>>,
    copies: AtomicUsize,
    frames_dropped: AtomicUsize,
}

impl Trace {
    fn step(&self, name: &'static str) {
        self.steps.lock().unwrap().push(name);
    }

    fn steps(&self) -> Vec<&'static str> {
        self.steps.lock().unwrap().clone()
    }
}

struct FakeBackend {
    container: Container,
    trace: Arc<Trace>,
    /// When non-zero, `open` refuses a stream shorter than this (a truncated container).
    min_bytes: u64,
}

impl EmbeddedThumbnailBackend for FakeBackend {
    fn open(
        &self,
        stream: Box<dyn ReadSeek>,
    ) -> Result<Option<Box<dyn EmbeddedThumbnailFrame>>, ThumbnailBackendError> {
        self.trace.step("open");
        let mut stream = stream;
        if self.min_bytes > 0 {
            let len = stream
                .seek(SeekFrom::End(0))
                .map_err(|e| ThumbnailBackendError(e.to_string()))?;
            if len < self.min_bytes {
                return Err(ThumbnailBackendError("truncated container".into()));
            }
        }
        match &self.container {
            Container::Refused => Err(ThumbnailBackendError("not an image".into())),
            Container::NoFrames => Ok(None),
            Container::Frame(spec) => Ok(Some(Box::new(FakeFrame {
                spec: spec.clone(),
                trace: Arc::clone(&self.trace),
                _stream: stream,
            }))),
        }
    }
}

struct FakeFrame {
    spec: FrameSpec,
    trace: Arc<Trace>,
    /// Owned like the WIC decoder owns its stream: released when the frame is dropped.
    _stream: Box<dyn ReadSeek>,
}

impl Drop for FakeFrame {
    fn drop(&mut self) {
        self.trace.frames_dropped.fetch_add(1, Ordering::SeqCst);
    }
}

impl EmbeddedThumbnailFrame for FakeFrame {
    fn main_size(&mut self) -> Result<(u32, u32), ThumbnailBackendError> {
        self.trace.step("main_size");
        let main = self.spec.main;
        main.map_err(|m| ThumbnailBackendError(m.into()))
    }

    fn thumbnail(&mut self) -> Option<Box<dyn EmbeddedThumbnailBitmap>> {
        self.trace.step("thumbnail");
        self.spec.thumbnail.clone().map(|bitmap| {
            Box::new(FakeBitmap {
                spec: bitmap,
                trace: Arc::clone(&self.trace),
            }) as Box<dyn EmbeddedThumbnailBitmap>
        })
    }

    fn orientation(&mut self) -> i32 {
        self.trace.step("orientation");
        self.spec.orientation
    }
}

struct FakeBitmap {
    spec: BitmapSpec,
    trace: Arc<Trace>,
}

impl EmbeddedThumbnailBitmap for FakeBitmap {
    fn size(&mut self) -> Result<(u32, u32), ThumbnailBackendError> {
        self.trace.step("size");
        let size = self.spec.size;
        size.map_err(|m| ThumbnailBackendError(m.into()))
    }

    fn copy_pbgra(&mut self, dst: &mut [u8], stride: usize) -> Result<(), ThumbnailBackendError> {
        self.trace.step("copy");
        self.trace.copies.fetch_add(1, Ordering::SeqCst);
        if self.spec.copy_error {
            return Err(ThumbnailBackendError("copy refused".into()));
        }
        assert!(
            stride >= 4 && dst.len() % stride == 0,
            "stride {stride} for {} bytes",
            dst.len()
        );
        for px in dst.chunks_exact_mut(4) {
            px.copy_from_slice(&self.spec.fill);
        }
        Ok(())
    }
}

