//! `pr_core::settings::perf_options` against the C# `PerformanceOptions` constants.
//!
//! Port of `PhotoReview.Core/Settings/PerformanceOptions.cs` (baseline e441d67a). The constants are asserted inside
//! settings tests in C#; these are the constant-only asserts plus the golden check (`tests/golden/perf-options.json`).

use pr_core::settings::perf_options::*;
use pr_test_support::golden;

const GIB: i64 = 1024 * 1024 * 1024;

// C#: ImageCacheRamPercentSettingsTests.Defaults_AreFiftyPercentWithinOneToNinety (constants only)
#[test]
fn image_cache_ram_percent_limits() {
    assert_eq!(IMAGE_CACHE_RAM_PERCENT, 50);
    assert_eq!(MAX_IMAGE_CACHE_RAM_PERCENT, 90);
    assert_eq!(MIN_IMAGE_CACHE_RAM_PERCENT, 1);
}

// C#: PreloadWindowSettingsTests.Defaults_Are32Forward8Backward (the PerformanceOptions.* lines only)
#[test]
fn preload_window_defaults_and_limits() {
    assert_eq!(PRELOAD_FORWARD_COUNT, 32);
    assert_eq!(PRELOAD_BACKWARD_COUNT, 8);
    assert_eq!(MIN_PRELOAD_FORWARD_COUNT, 1);
    assert_eq!(MIN_PRELOAD_BACKWARD_COUNT, 0);
    assert_eq!(MAX_PRELOAD_COUNT, 500);
}

// No C# twin: the four byte budgets must be exact GiB multiples, computed in i64 (16 * 1024^3 overflows i32).
#[test]
fn byte_budgets_are_gibibyte_multiples() {
    assert_eq!(IMAGE_CACHE_CAPACITY_BYTES, 16 * GIB);
    assert_eq!(MEMORY_RESERVE_BYTES, 2 * GIB);
    assert_eq!(PREVIEW_DISK_CACHE_CAPACITY_BYTES, 4 * GIB);
    assert_eq!(SOURCE_BYTES_CAPACITY_BYTES, 16 * GIB);
}

// No C# twin: every public const of PerformanceOptions (name, C# type, value) equals the golden value.
// Golden generated by tools/oracle-cs/Commands/W1-05.cs (`perf-options`).
#[test]
fn perf_options_match_golden() {
    let g = golden::load("perf-options");
    assert_eq!(g.cases.len(), 16);
    for case in &g.cases {
        let name = golden::str_of(case, "name");
        let ty = golden::str_of(case, "type");
        match name {
            "ImageCacheCapacityBytes" => {
                assert_eq!(ty, "Int64", "{name}");
                assert_eq!(golden::i64_of(case, "value"), IMAGE_CACHE_CAPACITY_BYTES, "{name}");
            }
            "ImageCacheRamPercent" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(IMAGE_CACHE_RAM_PERCENT),
                    "{name}"
                );
            }
            "MaxImageCacheRamPercent" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(MAX_IMAGE_CACHE_RAM_PERCENT),
                    "{name}"
                );
            }
            "MinImageCacheRamPercent" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(MIN_IMAGE_CACHE_RAM_PERCENT),
                    "{name}"
                );
            }
            "MemoryReserveBytes" => {
                assert_eq!(ty, "Int64", "{name}");
                assert_eq!(golden::i64_of(case, "value"), MEMORY_RESERVE_BYTES, "{name}");
            }
            "PreloadWorkerCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(golden::i64_of(case, "value"), i64::from(PRELOAD_WORKER_COUNT), "{name}");
            }
            "MaxPreloadWorkerCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(MAX_PRELOAD_WORKER_COUNT),
                    "{name}"
                );
            }
            "PreloadMemoryLoadLimit" => {
                assert_eq!(ty, "Double", "{name}");
                let value = case["value"]
                    .as_f64()
                    .unwrap_or_else(|| panic!("case has no number 'value': {case}"));
                assert!(
                    value == PRELOAD_MEMORY_LOAD_LIMIT,
                    "{name}: golden {value} vs {PRELOAD_MEMORY_LOAD_LIMIT}"
                );
            }
            "PreviewDiskCacheCapacityBytes" => {
                assert_eq!(ty, "Int64", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    PREVIEW_DISK_CACHE_CAPACITY_BYTES,
                    "{name}"
                );
            }
            "UseSourceBytesCache" => {
                assert_eq!(ty, "Boolean", "{name}");
                assert_eq!(golden::bool_of(case, "value"), USE_SOURCE_BYTES_CACHE, "{name}");
            }
            "SourceBytesCapacityBytes" => {
                assert_eq!(ty, "Int64", "{name}");
                assert_eq!(golden::i64_of(case, "value"), SOURCE_BYTES_CAPACITY_BYTES, "{name}");
            }
            "PreloadForwardCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(PRELOAD_FORWARD_COUNT),
                    "{name}"
                );
            }
            "PreloadBackwardCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(PRELOAD_BACKWARD_COUNT),
                    "{name}"
                );
            }
            "MinPreloadForwardCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(MIN_PRELOAD_FORWARD_COUNT),
                    "{name}"
                );
            }
            "MinPreloadBackwardCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(
                    golden::i64_of(case, "value"),
                    i64::from(MIN_PRELOAD_BACKWARD_COUNT),
                    "{name}"
                );
            }
            "MaxPreloadCount" => {
                assert_eq!(ty, "Int32", "{name}");
                assert_eq!(golden::i64_of(case, "value"), i64::from(MAX_PRELOAD_COUNT), "{name}");
            }
            other => panic!("unknown golden case {other:?}"),
        }
    }
}
