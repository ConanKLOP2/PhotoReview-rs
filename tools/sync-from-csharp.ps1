<#
.SYNOPSIS
  Copies the shared static assets (language catalogs, test fixtures) from the C# PhotoReview repo at one commit,
  and records that commit plus a SHA-256 per file in assets/SYNC-MANIFEST.txt.

.DESCRIPTION
  Reads from git objects (`git show <commit>:<path>`), not the C# working tree, so it never depends on, or touches,
  whatever branch the C# checkout is on. Only writes inside this repo.
  -Check: does not copy; fails if any local file differs from the manifest (CI-safe, no C# repo needed).

.EXAMPLE
  ./tools/sync-from-csharp.ps1 -CSharpRepo ..\PhotoReview -Commit origin/master
  ./tools/sync-from-csharp.ps1 -Check
#>
param(
    [string]$CSharpRepo,
    [string]$Commit = 'origin/master',
    [switch]$Check
)
$ErrorActionPreference = 'Stop'
if (-not $CSharpRepo -and -not $Check) {
    # Sibling of the MAIN checkout (also right when this runs from a worktree under .claude/worktrees/).
    $common = (& git -C $PSScriptRoot rev-parse --path-format=absolute --git-common-dir).Trim()
    $CSharpRepo = Join-Path (Split-Path (Split-Path $common)) 'PhotoReview'
}
$root = Resolve-Path (Join-Path $PSScriptRoot '..')
$manifest = Join-Path $root 'assets\SYNC-MANIFEST.txt'

# C# path prefix -> local folder
$map = [ordered]@{
    'src/PhotoReview.Core/Localization/Languages/' = 'assets/languages/'
    'tests/Fixtures/'                              = 'tests/fixtures/'
}

function Get-Sha256([string]$path) { (Get-FileHash -Algorithm SHA256 -LiteralPath $path).Hash.ToLowerInvariant() }

if ($Check) {
    if (-not (Test-Path $manifest)) { throw "Missing $manifest" }
    $bad = 0
    foreach ($line in Get-Content $manifest) {
        if ($line -match '^\s*(#|$)') { continue }
        $hash, $rel = $line -split '  ', 2
        $full = Join-Path $root $rel
        if (-not (Test-Path -LiteralPath $full)) { Write-Host "MISSING  $rel"; $bad++; continue }
        if ((Get-Sha256 $full) -ne $hash) { Write-Host "CHANGED  $rel"; $bad++ }
    }
    if ($bad) { throw "$bad synced file(s) differ from assets/SYNC-MANIFEST.txt; re-run the sync instead of editing them here." }
    Write-Host 'Synced assets match the manifest.'
    return
}

$sha = (& git -C $CSharpRepo rev-parse --verify "$Commit^{commit}").Trim()
if ($LASTEXITCODE -ne 0) { throw "Cannot resolve $Commit in $CSharpRepo" }

$lines = @("# Source: C# PhotoReview commit $sha", "# Generated by tools/sync-from-csharp.ps1; do not edit by hand.")
foreach ($prefix in $map.Keys) {
    $dest = Join-Path $root $map[$prefix]
    if (Test-Path $dest) { Get-ChildItem -LiteralPath $dest -Recurse -File | Remove-Item -Force -Confirm:$false }
    $files = & git -C $CSharpRepo ls-tree -r --name-only $sha -- $prefix
    foreach ($file in $files) {
        $rel = $map[$prefix] + $file.Substring($prefix.Length)
        $out = Join-Path $root $rel
        New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
        # Raw bytes via cmd redirection would mangle encodings; git cat-file through a .NET process keeps them exact.
        $psi = New-Object System.Diagnostics.ProcessStartInfo 'git', "-C `"$CSharpRepo`" cat-file blob `"$sha`:$file`""
        $psi.RedirectStandardOutput = $true; $psi.UseShellExecute = $false
        $proc = [System.Diagnostics.Process]::Start($psi)
        $fs = [System.IO.File]::Create($out)
        try { $proc.StandardOutput.BaseStream.CopyTo($fs) } finally { $fs.Dispose() }
        $proc.WaitForExit()
        if ($proc.ExitCode -ne 0) { throw "git cat-file failed for $file" }
        $lines += "$(Get-Sha256 $out)  $rel"
    }
}
$lines | Set-Content -Encoding utf8 $manifest
Write-Host "Synced $($lines.Count - 2) file(s) from $sha. Record the new baseline in docs/SYNC-LEDGER.md."
